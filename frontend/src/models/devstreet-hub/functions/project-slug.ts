/** Normalise un titre en slug URL (minuscules, tirets, sans accents). */
export function slugifyProjectTitle(title: string, maxLength = 100): string {
  return title
    .normalize("NFD")
    .replace(/\p{M}/gu, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, maxLength)
    .replace(/-+$/g, "");
}
